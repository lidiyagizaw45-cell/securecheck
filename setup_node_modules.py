class ProgressBar:
    """Renders a smooth animated percentage progress bar in console."""
    def __init__(self, total_stages=100):
        self.pct = 0
        self.label = "Initializing..."
        self.running = False
        self._thread = None
        self._lock = threading.Lock()

    def render(self):
        with self._lock:
            val = max(0, min(100, int(self.pct)))
            bar_len = 26
            filled = int(bar_len * val / 100)
            bar = "=" * filled + (">" if filled < bar_len else "")
            bar = bar.ljust(bar_len, " ")
            line = f"  [{bar}] {val:3d}% | {self.label}"
            sys.stdout.write(f"\r{line:<75}")
            sys.stdout.flush()

    def set_progress(self, target_pct, label=None):
        self.stop_smooth()
        self.pct = target_pct
        if label:
            self.label = label
        self.render()

    def start_smooth(self, target_pct, duration=15.0, label=None):
        self.stop_smooth()
        if label:
            self.label = label
        self.running = True
        
        def _ticker():
            interval = 0.2
            start = self.pct
            steps = int(duration / interval)
            delta = (target_pct - start) / max(1, steps)
            while self.running and self.pct < target_pct:
                time.sleep(interval)
                self.pct = min(target_pct, self.pct + delta)
                self.render()

        self._thread = threading.Thread(target=_ticker, daemon=True)
        self._thread.start()

    def stop_smooth(self, final_pct=None, label=None):
        self.running = False
        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=0.3)
        if final_pct is not None:
            self.pct = final_pct
        if label:
            self.label = label
        self.render()

    def finish_line(self):
        print()

progress = ProgressBar()

def print_header(text):
    print("\n" + "=" * 70)
    print(f"  {text}")
    print("=" * 70)

def find_executable(name, extra_paths=None):
    """Finds an executable in system PATH or common installation directories."""
    path = shutil.which(name)
    if path:
        return path
    
    if platform.system() == "Windows":
        name_exts = [f"{name}.cmd", f"{name}.exe", f"{name}.bat", name]
        search_dirs = [
            os.environ.get("ProgramFiles", r"C:\Program Files") + r"\nodejs",
            os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)") + r"\nodejs",
            os.path.expandvars(r"%LOCALAPPDATA%\Programs\node"),
            os.path.expandvars(r"%APPDATA%\npm"),
            os.path.expandvars(r"%USERPROFILE%\AppData\Roaming\npm"),
            r"C:\Program Files\nodejs",
            r"C:\Program Files (x86)\nodejs",
        ]
        if extra_paths:
            search_dirs.extend(extra_paths)
            
        for d in search_dirs:
            if os.path.exists(d):
                for ext in name_exts:
                    full_path = os.path.join(d, ext)
                    if os.path.exists(full_path) and os.path.isfile(full_path):
                        if d not in os.environ["PATH"]:
                            os.environ["PATH"] = d + os.pathsep + os.environ["PATH"]
                        return full_path
    return None

def check_and_install_python_deps():
    print_header("[1/3] Backend Python Environment & Dependencies")
    progress.set_progress(10, "Detecting Python runtime...")
    time.sleep(0.3)
    
    python_exe = sys.executable
    progress.set_progress(15, f"Python verified ({sys.version.split()[0]})")
    progress.finish_line()
    print(f"  [OK] Python Interpreter: {python_exe}")
    
    if not os.path.exists(REQUIREMENTS_TXT):
        print(f"  [ERROR] Requirements file not found: {REQUIREMENTS_TXT}")
        return False
        
    print(f"  [INFO] Installing Python packages from backend/requirements.txt...")
    progress.start_smooth(40, duration=10.0, label="Installing FastAPI, PyMongo, Pydantic...")
    
    try:
        subprocess.run([python_exe, "-m", "pip", "install", "--upgrade", "pip", "--quiet"], check=False)
        subprocess.run([python_exe, "-m", "pip", "install", "-r", REQUIREMENTS_TXT, "--quiet"], check=True)
        progress.stop_smooth(45, "Python backend dependencies ready.")
        progress.finish_line()
        print("  [OK] Python backend dependencies installed successfully.")
    except Exception as e:
        progress.stop_smooth(45, "Python dependency installation warning")
        progress.finish_line()
        print(f"  [WARNING] pip install warning: {e}")
        
    # Setup .env
    progress.set_progress(48, "Initializing backend configuration & data directory...")
    if not os.path.exists(ENV_FILE):
        if os.path.exists(ENV_EXAMPLE):
            try:
                shutil.copy(ENV_EXAMPLE, ENV_FILE)
                print(f"  [OK] Created '{ENV_FILE}' from template.")
            except Exception as e:
                print(f"  [WARNING] Copying .env.example failed: {e}")
        else:
            try:
                with open(ENV_FILE, "w", encoding="utf-8") as f:
                    f.write("MONGODB_URI=mongodb://localhost:27017\n")
                    f.write("DATABASE_NAME=securecheck_db\n")
                    f.write("OPENROUTER_API_KEY=\n")
                    f.write("OPENROUTER_MODEL=openai/gpt-4o-mini\n")
                print(f"  [OK] Generated default '{ENV_FILE}'.")
            except Exception as e:
                print(f"  [WARNING] Creating .env failed: {e}")
    else:
        print(f"  [OK] Backend .env is present.")

    # Ensure backend/data folder exists for offline database
    data_dir = os.path.join(BACKEND_DIR, "data")
    os.makedirs(data_dir, exist_ok=True)
    print(f"  [OK] Backend offline data directory initialized: backend/data")

    # Ensure launcher batch files exist
    create_launcher_scripts_if_missing()
    
    progress.set_progress(50, "Backend stage complete.")
    progress.finish_line()
    return True

def create_launcher_scripts_if_missing():
    """Auto-generates run_project.bat, start.bat, and install_requirements.bat if missing."""
    run_proj = os.path.join(PROJECT_ROOT, "run_project.bat")
    if not os.path.exists(run_proj):
        try:
            with open(run_proj, "w", encoding="utf-8") as f:
                f.write('@echo off\n')
                f.write('setlocal EnableDelayedExpansion\n')
                f.write('title SecureCheck - Launcher\n')
                f.write('color 0A\n')
                f.write('cd /d "%~dp0"\n')
                f.write('if not exist "frontend\\node_modules\\" call "%~dp0setup_node_modules.bat"\n')
                f.write('start "SecureCheck Backend API" cmd /k "cd /d \"%~dp0backend\" && python -m uvicorn app.main:app --reload --port 8000"\n')
                f.write('start "SecureCheck Frontend" cmd /k "cd /d \"%~dp0frontend\" && npm run dev"\n')
                f.write('timeout /t 4 /nobreak >nul\n')
                f.write('start http://localhost:5173\n')
                f.write('echo SecureCheck is running at http://localhost:5173\n')
            print(f"  [OK] Auto-generated missing launcher: run_project.bat")
        except Exception:
            pass

    start_bat = os.path.join(PROJECT_ROOT, "start.bat")
    if not os.path.exists(start_bat):
        try:
            with open(start_bat, "w", encoding="utf-8") as f:
                f.write('@echo off\n')
                f.write('cd /d "%~dp0"\n')
                f.write('start "SecureCheck Backend" cmd /k "cd /d \"%~dp0backend\" && python -m uvicorn app.main:app --reload --port 8000"\n')
                f.write('start "SecureCheck Frontend" cmd /k "cd /d \"%~dp0frontend\" && npm run dev"\n')
            print(f"  [OK] Auto-generated missing launcher: start.bat")
        except Exception:
            pass

def inspect_package_json():
    """Validates and prints the packages required by the frontend project."""
    if not os.path.exists(PACKAGE_JSON):
        print(f"  [ERROR] File not found: {PACKAGE_JSON}")
        return None
        
    try:
        with open(PACKAGE_JSON, "r", encoding="utf-8") as f:
            data = json.load(f)
            
        deps = data.get("dependencies", {})
        dev_deps = data.get("devDependencies", {})
        
        print("  [INFO] Project Packages Declared in frontend/package.json:")
        print("    Dependencies:")
        for pkg, ver in deps.items():
            print(f"      - {pkg}: {ver}")
        print("    Dev Dependencies:")
        for pkg, ver in dev_deps.items():
            print(f"      - {pkg}: {ver}")
        return data
    except Exception as e:
        print(f"  [ERROR] Reading package.json failed: {e}")
        return None

def create_frontend_node_modules():
    print_header("[2/3] Frontend Node Modules Installation")
    progress.set_progress(52, "Inspecting frontend/package.json...")
    
    # 1. Check package.json
    pkg_data = inspect_package_json()
    if not pkg_data:
        return False
        
    # 2. Locate node and npm
    progress.set_progress(55, "Locating Node.js and NPM binaries...")
    node_bin = find_executable("node")
    npm_bin = find_executable("npm")
    
    if not node_bin or not npm_bin:
        progress.finish_line()
        print("\n  [ERROR] Node.js and NPM were not found in standard system PATH.")
        print("  Please install Node.js (v18, v20, or v22 LTS recommended) from:")
        print("    --> https://nodejs.org/")
        print("  After installing Node.js, run this script again or double click 'setup_node_modules.bat'.")
        return False
        
    print(f"\n  [OK] Found Node.js : {node_bin}")
    print(f"  [OK] Found NPM     : {npm_bin}")
    
    # 3. Clean stale lockfile if needed
    lock_file = os.path.join(FRONTEND_DIR, "package-lock.json")
    
    print("\n  [INFO] Downloading and building node_modules packages in frontend/...")
    progress.start_smooth(88, duration=20.0, label="Downloading & extracting npm packages...")
    
    strategies = [
        ("Standard npm install (--legacy-peer-deps)", [npm_bin, "install", "--legacy-peer-deps"]),
        ("Force npm install (--force)", [npm_bin, "install", "--force"]),
        ("Fresh npm install without lockfile", [npm_bin, "install", "--legacy-peer-deps", "--no-audit", "--no-fund"])
    ]
    
    success = False
    for desc, cmd in strategies:
        try:
            res = subprocess.run(cmd, cwd=FRONTEND_DIR, shell=(platform.system() == "Windows"), capture_output=True, text=True)
            if res.returncode == 0:
                success = True
                progress.stop_smooth(90, f"npm packages downloaded successfully.")
                progress.finish_line()
                print(f"  [OK] Success with: {desc}")
                break
            else:
                if desc.startswith("Force") and os.path.exists(lock_file):
                    try:
                        os.remove(lock_file)
                    except Exception:
                        pass
        except Exception as e:
            pass
            
    if not success:
        # Try direct interactive execution if silent failed
        try:
            res = subprocess.run([npm_bin, "install", "--legacy-peer-deps"], cwd=FRONTEND_DIR, shell=(platform.system() == "Windows"))
            success = (res.returncode == 0)
        except Exception:
            pass

    # Verify node_modules creation
    progress.set_progress(92, "Verifying installed packages on disk...")
    if os.path.exists(NODE_MODULES) and os.path.isdir(NODE_MODULES):
        installed_pkgs = os.listdir(NODE_MODULES)
        progress.set_progress(95, f"Verified {len(installed_pkgs)} packages in node_modules")
        progress.finish_line()
        print(f"  [OK] node_modules directory: {NODE_MODULES}")
        print(f"  [OK] Total packages/directories installed: {len(installed_pkgs)}")
        
        # Verify key packages
        key_pkgs = ["react", "react-dom", "vite", "bootstrap", "axios"]
        missing_key = [p for p in key_pkgs if not os.path.exists(os.path.join(NODE_MODULES, p))]
        if not missing_key:
            print(f"  [OK] All core runtime packages verified: {', '.join(key_pkgs)}")
            return True
        else:
            print(f"  [WARNING] Some core packages were not found in node_modules: {missing_key}")
            return success
    else:
        progress.finish_line()
        print(f"\n  [ERROR] Failed to create {NODE_MODULES}")
        return False

